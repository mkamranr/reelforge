_IMAGE_CACHE = {{}}


def _load_image(name):
    """Open a prepared screenshot once per process.

    Each parallel chunk is its own process, so this caches within a chunk and
    the file is read a handful of times rather than once per frame.
    """
    if name not in _IMAGE_CACHE:
        path = os.path.join(HERE_IMAGES, name)
        _IMAGE_CACHE[name] = Image.open(path).convert("RGBA")
    return _IMAGE_CACHE[name]


def _rounded(img, radius):
    """Round an image's corners, so it sits on the ground like every card."""
    mask = Image.new("L", img.size, 0)
    ImageDraw.Draw(mask).rounded_rectangle(
        (0, 0, img.width - 1, img.height - 1), radius=radius, fill=255)
    out = img.copy()
    out.putalpha(mask)
    return out


_EDGE_FADE = [None]


def _edge_fade():
    """A mask that fades a full-bleed image into the ground at every edge.

    The safe-area check measures legibility, not difference, because these
    storyboards use full-bleed decorative layers by design. A bright screenshot
    run edge to edge is legible in the corners -- which is where the platform's
    own UI sits, so a viewer never reads it and the check is right to say so.

    Fading the edges makes the frame honestly safe rather than silencing the
    check: the centre stays sharp and carries the screenshot, the outer band
    becomes ground, and burned-in captions over the lower third stay readable.
    """
    if _EDGE_FADE[0] is None:
        import math as _math

        import numpy as _np

        def ramp(length, lead, tail):
            """Fade in over `lead` and out over `tail`, passing through
            EDGE_AT_SAFE where the safe area begins."""
            out = _np.ones(length)
            for span, target in ((lead, "lead"), (tail, "tail")):
                if not span:
                    continue
                # solve p so (safe/span)**p == EDGE_AT_SAFE
                safe = min(max(span * 0.5, 1.0), span - 1.0)
                power = _math.log(EDGE_AT_SAFE) / _math.log(safe / span)
                curve = _np.linspace(0.0, 1.0, span) ** power
                if target == "lead":
                    out[:span] = curve
                else:
                    out[length - span:] = curve[::-1]
            return out

        # twice the safe margin, so the ramp is well under way by the boundary
        columns = ramp(W, SAFE_SIDE * 2, SAFE_SIDE * 2)
        rows = ramp(H, SAFE_TOP * 2, (H - SAFE_BOTTOM) * 2)
        field = _np.outer(rows, columns) * 255.0
        _EDGE_FADE[0] = Image.fromarray(field.astype("uint8"), "L")
    return _EDGE_FADE[0]


_SCRIM_CACHE = {{}}


_SIDE_FADE = {{}}


def _side_fade(height):
    """Fade a full-width panel's left and right bands into the ground.

    A panel that spans the frame necessarily reaches x 0 and x 1080, outside the
    safe area -- the same thing full-bleed does, for the same reason, and the
    safe-area check is right to flag it either way. Fading the sides makes the
    band under the platform UI decorative instead of information nobody sees.
    """
    if height not in _SIDE_FADE:
        import math as _math

        import numpy as _np

        span = SAFE_SIDE * 2
        power = _math.log(EDGE_AT_SAFE) / _math.log(0.5)
        curve = _np.linspace(0.0, 1.0, span) ** power
        columns = _np.ones(W)
        columns[:span] = curve
        columns[W - span:] = curve[::-1]
        field = _np.tile(columns, (height, 1)) * 255.0
        _SIDE_FADE[height] = Image.fromarray(field.astype("uint8"), "L")
    return _SIDE_FADE[height]


def _bottom_scrim(k):
    """A gradient over the lower band of a full-bleed image."""
    key = round(k, 2)
    if key not in _SCRIM_CACHE:
        import numpy as _np

        depth = H - BOTTOM_SCRIM_TOP
        ramp = _np.zeros(H)
        ramp[BOTTOM_SCRIM_TOP:] = (
            _np.linspace(0.0, 1.0, depth) ** 1.4) * BOTTOM_SCRIM_MAX * key
        layer = _np.zeros((H, W, 4), dtype="uint8")
        layer[:, :, 3] = (ramp[:, None] * 255).astype("uint8")
        _SCRIM_CACHE[key] = Image.fromarray(layer, "RGBA")
    return _SCRIM_CACHE[key]


def sl_image(ov, d, t, t0, o):
    """A screenshot: the one thing on screen the pipeline did not draw itself.

    `panel` keeps the whole image inside a card on the reel's own ground, which
    is how the shipped storyboards present a terminal. `full` fills the frame
    and takes a scrim, because burned-in captions sit over the lower third and a
    bright screenshot underneath makes them unreadable.
    """
    k, dy = enter(t, t0 + o.get("delay", 0.10), 0.40, 26)
    if k <= 0:
        return
    img = _load_image(o["file"])

    if o.get("fit") == "full":
        # into ov, not via d.rectangle: ImageDraw replaces pixels rather than
        # blending, and would erase the layer (gotcha 1)
        faded = img.copy()
        alpha = ImageChops.multiply(img.getchannel("A"), _edge_fade())
        faded.putalpha(alpha.point(lambda a: int(a * k)))
        ov.alpha_composite(faded, (0, 0))
        S.scrim(ov, FULL_BLEED_DIM * k)
        ov.alpha_composite(_bottom_scrim(k))
        if o.get("label"):
            text(d, (W // 2, 1300 if CAPTIONS else 1460), o["label"],
                 _fit(o["label"], 56, "bold"), WHITE, k, 2, "mb")
        return

    # A panel spans the full frame width, so it is rounded only where it does
    # not meet an edge -- a rounded corner against the frame edge reads as a
    # mistake rather than a card.
    card = _rounded(img, 22) if img.width < W else img.copy()
    y = int(o.get("y", 430) + dy)
    x = (W - card.width) // 2
    if card.width < W:
        d.rounded_rectangle((x - 2, y - 2, x + card.width + 1, y + card.height + 1),
                            radius=24, outline=rgba(TH.border, 0.95 * k), width=2)
    else:
        d.line((0, y - 1, W, y - 1), fill=rgba(TH.border, 0.8 * k), width=2)
        d.line((0, y + card.height, W, y + card.height),
               fill=rgba(TH.border, 0.8 * k), width=2)
    faded = card.copy()
    alpha = card.getchannel("A")
    if card.width >= W:
        alpha = ImageChops.multiply(alpha, _side_fade(card.height))
    faded.putalpha(alpha.point(lambda a: int(a * k)))
    ov.alpha_composite(faded, (x, y))

    caption = o.get("caption") or o.get("label")
    if caption:
        # above the image, never below: a panel at the bottom of the band ends
        # where the burned-in captions begin, and two lines of text in the same
        # place means neither can be read
        text(d, (W // 2, y - 34), caption,
             _fit(caption, 30 if o.get("caption") else 40, "med" if o.get("caption") else "bold"),
             TH.muted if o.get("caption") else WHITE, k, 0, "mb")


def sl_scroll(ov, d, t, t0, o):
    """The repo page, panned top to bottom inside the panel band.

    Bloom burns captions in, so this pans within the band rather than full
    bleed -- caption text over a scrolling README is unreadable, and the band
    is exactly the room a panel already has.
    """
    try:
        img = _load_image(o.get("file", ""))
    except Exception:
        return
    if img.width != W:
        img = img.resize((W, int(img.height * W / img.width)), Image.LANCZOS)
    top = 380
    band = min(1060, (1440 if DATA.get("captions", True) else 1580) - top)
    dur = float(o.get("dur", 8.0))
    k = eo3(lin(t, t0, t0 + 0.34))
    if k <= 0.01:
        return
    # Distance is speed x time, not "the whole page however tall it is".
    # Fitting a 8768px page into a 6s scene meant ~1600 px/s and read as a
    # blur; showing the repo is the point, not reaching its footer.
    p = clamp((t - t0 - 0.34) / max(dur - 0.34, 0.01))
    hold, speed = 0.12, float(o.get("speed", 300))
    travel = min(max(0, img.height - band), speed * (dur - 0.34) * (1.0 - hold))
    q = clamp((p - hold) / max(1.0 - hold, 0.05))
    q = q * q * (3.0 - 2.0 * q)
    y = int(q * travel)
    crop = _rounded(img.crop((0, y, W, min(y + band, img.height))).convert("RGBA"), 22)
    # a README is a white page and this panel spans the frame, so the side
    # bands take the same fade the full-width screenshots take
    crop.putalpha(ImageChops.multiply(crop.getchannel("A"), _side_fade(crop.height)))
    ov.alpha_composite(crop, (0, top))
    label = o.get("label") or DATA["tag"]
    if label:
        text(d, (W // 2, top - 30), label, m(30, "bold"), TH.accent_hi, k, 2, "mb")



# ---- generated clips -------------------------------------------------------
# A clip is a directory of JPEG frames at the reel's own size and frame rate,
# extracted once by the visuals stage, so drawing it is pasting frame n --
# exactly what the repo scroll does with one tall PNG, for the same reason:
# the renderer is a PIL frame pump and cannot decode video.
_CLIP_CACHE = {{}}
_CLIP_ORDER = []


def _clip_frame(dirname, index):
    """One frame, behind a small LRU: a chunk process holds a handful of
    decoded frames rather than a whole clip."""
    key = (dirname, index)
    if key in _CLIP_CACHE:
        return _CLIP_CACHE[key]
    path = os.path.join(HERE_IMAGES, dirname, "%05d.jpg" % (index + 1))
    try:
        img = Image.open(path).convert("RGBA")
    except Exception:
        img = None
    _CLIP_CACHE[key] = img
    _CLIP_ORDER.append(key)
    while len(_CLIP_ORDER) > 12:
        _CLIP_CACHE.pop(_CLIP_ORDER.pop(0), None)
    return img


def _clip_index(t, t0, fps, n):
    """Ping-pong through the frames, so a scene longer than its clip turns
    around instead of jumping back to the first frame."""
    if n <= 1:
        return 0
    i = int(max(0.0, t - t0) * fps)
    cycle = 2 * (n - 1)
    i %= cycle
    return i if i < n else cycle - i


def _band_scrim(colour, height, solid, fade, flip=False):
    """Solid `colour` for `solid` rows then a fade over `fade` rows -- the
    shape the slab scroll uses so chrome stays legible over a picture."""
    key = ("scrim", tuple(colour), height, solid, fade, flip)
    if key not in _CLIP_CACHE:
        layer = Image.new("RGBA", (W, height), (0, 0, 0, 0))
        ld = ImageDraw.Draw(layer)
        for row in range(height):
            r = height - 1 - row if flip else row
            a = 1.0 if r < solid else max(0.0, 1.0 - (r - solid) / max(1, fade))
            ld.line((0, row, W, row), fill=rgba(colour, a))
        _CLIP_CACHE[key] = layer
    return _CLIP_CACHE[key]


def sl_clip(ov, d, t, t0, o):
    """A generated clip, full bleed under the eyebrow and the captions.

    Treated like a `full` screenshot: edge fade, the same dim scrim, the
    bottom scrim so burned-in captions stay readable over moving picture.
    """
    k = eo3(lin(t, t0, t0 + 0.40))
    if k <= 0.01:
        return
    img = _clip_frame(o["dir"], _clip_index(t, t0, int(o.get("fps", 30)), int(o.get("frames", 1))))
    if img is None:
        return
    faded = img.copy()
    alpha = ImageChops.multiply(img.getchannel("A"), _edge_fade())
    faded.putalpha(alpha.point(lambda a: int(a * k)))
    ov.alpha_composite(faded, (0, 0))
    S.scrim(ov, FULL_BLEED_DIM * k)
    ov.alpha_composite(_bottom_scrim(k))
    # the scene's title over the bottom scrim, so a dark clip still carries
    # a line of text and the screen is never just a picture under an eyebrow
    if o.get("label"):
        text(d, (W // 2, 1300 if CAPTIONS else 1460), o["label"],
             _fit(o["label"], 48, "bold"), WHITE, k, 2, "mb")



def _fit_line(value, face, track, budget, url=False):
    """The end cards draw their lines at fixed sizes; the strings bend instead.

    A URL loses its host first -- the path is the identity, the host is
    boilerplate -- and anything still too wide is ellipsis-trimmed. Measured
    with the same face and tracking the card will draw with, because whether
    a line fits depends on which letters it uses."""
    if not value:
        return value
    out = str(value)
    if tw(out, face, track) <= budget:
        return out
    if url and "/" in out:
        out = out.split("/", 1)[1]
        if tw(out, face, track) <= budget:
            return out
    while out and tw(out + "\\u2026", face, track) > budget:
        out = out[:-1]
    return (out.rstrip() + "\\u2026") if out else str(value)[:8]


def sl_endcard(ov, d, t, t0, o):
    # start the entrance before the cut, so the frame just after the cut is
    # already substantially drawn rather than a near-empty fade-up
    budget = W - 2 * MARGIN
    endcard(ov, d, t, t0 - 0.30, TH, DATA["wordmark"],
            _fit_line(DATA["endcard_sub"], m(38), 3, budget),
            _fit_line(DATA["url"], m(40, "bold"), 0, budget, url=True),
            _fit_line(DATA["url2"], m(34), 0, budget, url=True),
            _fit_line(DATA["cta"], f(40, "bold"), 4, budget - 112),
            mark_size=DATA["mark_size"])



"""Emit a storyboard module from content data alone.

Two jobs. It is the floor under code generation -- when the repair budget runs
out, a job still produces a video rather than nothing -- and it is the
`safe-deterministic` template a user can choose on purpose.

It writes source rather than being imported directly because the whole pipeline
below it expects a module in `storyboards/` with the standard contract: the
renderer imports by name, `sfx.py` reads `SFX` off the module, and `make.sh`
reads `AUDIO` and `PHRASES`. Emitting a real module keeps that one path.

Scene boundaries are taken from the alignment at import time, not from the
script's intended timecodes, so the cuts land on the narration however the
delivery actually came out.
"""

def _fit_mark(word, start=250, floor=64):
    """Largest wordmark size that stays inside the safe width.

    `sbkit.endcard` draws the wordmark centred at a fixed size, so a long name
    runs off both edges -- "Harness Open Source" at 250px is far wider than the
    frame. It accepts a size, so the size is measured rather than assumed.
    """
    avail = W - 2 * MARGIN
    size = start
    while size > floor and tw(word, f(size, "bold"), 0) > avail:
        size -= 6
    return size

#: Prepared screenshots live beside the storyboard, inside the job workspace,
#: so `os.path.abspath(__file__)` finds them the same way `build/` is found.
#: The safe area, which is what the fade is shaped around: outside it the
#: platform's own UI sits on top, so anything legible there is content the
#: viewer never sees.
SAFE_TOP, SAFE_BOTTOM, SAFE_SIDE = 150, 1600, 84

#: What the image is scaled to at the safe boundary. Derived rather than
#: guessed: a linear ramp that merely *starts* at the frame edge is still 83%
#: opaque by the boundary, which is exactly what the safe-area check reported.
#: The exponent below is solved so the ramp passes through this value there.
#:
#: Measured against a near-white screenshot, the worst case: 0.45 passes the
#: safe-area check and 0.6 does not, so this sits just inside the margin and
#: shows as much of the image as the rule allows.
EDGE_AT_SAFE = 0.42

#: A full-bleed image also takes a gradient over its lower third, starting well
#: above the safe boundary. Two reasons, and both are about the same band: the
#: platform draws its caption bar and action buttons there, so anything legible
#: is content the viewer never sees; and burned-in captions sit on top of it.
#: A gradient reads as deliberate where a hard fade reads as a black bar.
BOTTOM_SCRIM_TOP, BOTTOM_SCRIM_MAX = 1180, 0.82

#: A light overall dim under a full-bleed image, so the eyebrow pill and the
#: repo tag in the corner stay readable over a bright screenshot. Light-mode
#: screenshots are near-white, and chrome drawn in white over white is not
#: chrome anyone can see.
FULL_BLEED_DIM = 0.16

HERE_IMAGES = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "images")


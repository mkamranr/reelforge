def _fit_mono(text, size, avail, track=0):
    """Trim to fit a size sbkit will not let us change, on a word boundary.

    Dropping one character at a time fits, and reads as broken: the end card
    showed "Drone's successor adds SCM, Gitspac". Backing up to the last space
    costs a word and looks deliberate.
    """
    original = text
    while text and tw(text, m(size), track) > avail:
        text = text[:-1]
    if text == original:
        # it fits as written -- do not touch it. Backing off unconditionally
        # turned "docker run -d" into "docker run", which is a different
        # command, and a command on screen has to be the one that works.
        return text
    head, space, _tail = text.rpartition(" ")
    if space and len(head) > len(text) * 0.5:
        text = head
    return text.rstrip(" ,.;:-")



def _fit(txt, size, weight="bold", avail=None):
    """Largest size at or below `size` whose text fits the safe width.

    The fallback has to survive whatever the content stage produced. Drawing at
    a fixed size meant a long hook line ran off both edges and tripped the
    safe-area check -- which failed the one storyboard that is supposed to be
    unfailable.
    """
    avail = avail if avail is not None else W - 2 * MARGIN
    step = size
    while step > 24:
        font = f(step, weight)
        if tw(txt, font, 0) <= avail:
            return font
        step -= 4
    return f(24, weight)


def _headline(ov, d, t, t0, lines, y=560, size=86, sub=None):
    fonts = [_fit(line, size) for line in lines]
    heights = [fnt.size + 16 for fnt in fonts]
    for row, (line, font) in enumerate(zip(lines, fonts)):
        k, dy = enter(t, t0 + row * 0.16, 0.36, 30)
        if k <= 0:
            continue
        text(d, (W // 2, y + sum(heights[:row]) + dy), line, font, WHITE, k, 0, "mt")
    if sub:
        k, dy = enter(t, t0 + 0.20 + 0.16 * len(lines), 0.36, 22)
        text(d, (W // 2, y + sum(heights) + 40 + dy), sub,
             _fit(sub, 38, "med"), TH.pale, k, 0, "mt")



#: A screen held longer than this stops reading as a cut and starts reading as
#: a slideshow. DEVELOPMENT.md: a cut every 2-4 seconds, and if a layout must hold
#: longer, give it an event every 1-2 seconds inside the hold.
MAX_SCENE_SECONDS = 5.5

#: The smoke check's floor: nothing reads in under this.
MIN_SCENE_SECONDS = 1.2


def scene_spans(segments: list[tuple[float, float]], phrase_scene: list[int],
                total: float, endcard_seconds: float) -> list[tuple[float, float]]:
    """Cut on the narration, not on round numbers.

    Each script scene owns a contiguous run of phrases and ends where its last
    phrase ends, so nothing is left on screen after the line that pays it off.
    A run that would hold past MAX_SCENE_SECONDS is split at the phrase boundary
    nearest that limit, which keeps the rhythm without ever cutting mid-sentence.
    """
    groups, current = [], None
    for phrase_index, scene_index in enumerate(phrase_scene):
        if scene_index != current:
            groups.append([phrase_index])
            current = scene_index
        else:
            groups[-1].append(phrase_index)

    spans, cursor = [], 0.0
    for members in groups:
        run_start = cursor
        for position, phrase_index in enumerate(members):
            # a segment cannot end after the audio does; clamping here keeps
            # every later span arithmetic total-safe
            end = min(segments[min(phrase_index, len(segments) - 1)][1], total)
            if end - run_start >= MAX_SCENE_SECONDS or position == len(members) - 1:
                spans.append((run_start, end))
                run_start = end
        cursor = run_start

    if not spans:
        return [(0.0, total)]

    # Where the end card starts. Preferring `total - endcard_seconds` would cut
    # the last line off when the narration runs long, and preferring the end of
    # the narration gives the end card whatever is left -- which can be nothing,
    # or negative, when the recording has no tail silence. Both ends are
    # clamped: no scene reads in under MIN_SCENE_SECONDS.
    preferred = max(total - endcard_seconds, spans[-1][1] + 0.5)
    earliest = spans[-1][0] + MIN_SCENE_SECONDS
    latest = total - MIN_SCENE_SECONDS
    if earliest <= latest:
        tail = min(max(preferred, earliest), latest)
    else:
        # too short to give both a readable hold; split what there is
        tail = (spans[-1][0] + total) / 2

    spans[-1] = (spans[-1][0], tail)
    spans.append((tail, total))

    # Fewer segments than phrases -- an alignment that never ran, or a caller
    # that forgot to pass one -- makes every group end at the same instant, so
    # every span after the first is zero-length. That renders as a stack of
    # screens nobody sees. An even split is wrong about where the cuts belong
    # but right about there being cuts at all, so it degrades instead of
    # producing a table the smoke check has to reject.
    if any(end - start < MIN_SCENE_SECONDS for start, end in spans):
        count = max(len(spans), 2)
        step = total / count
        spans = [(round(i * step, 3), round((i + 1) * step, 3)) for i in range(count)]
        spans[-1] = (spans[-1][0], total)
    return spans


def _resolve(slot, bundle: dict, variant: int) -> dict | None:
    """Turn a catalogue slot into concrete drawing data, or drop it.

    Returning None is how a layout degrades: a factlist with nothing left to
    show is omitted rather than drawn empty. `variant` slides the window into
    the source list, so a layout that has to appear twice shows the next rows
    rather than the same ones.
    """
    kind, options = slot.kind, dict(slot.options)
    source = options.pop("source", None)
    out = {"kind": kind} | options

    if kind == "endcard":
        return out
    if kind == "headline":
        lines = list(bundle.get(source) or [])
        if not lines:
            return None
        out["lines"] = [_clip(line, 34) for line in lines[:3]]
        # `sub: tagline` names a key in the bundle, not the literal word
        if out.get("sub"):
            out["sub"] = _clip(str(bundle.get(out["sub"], "") or ""), 56) or None
    elif kind == "quote":
        value = bundle.get(source)
        if not value:
            return None
        out["lines"] = _wrap(str(value), 22, 3)
    elif kind == "statcards":
        stats = list(bundle.get(source) or [])
        if not stats:
            return None
        out["stats"] = [[_clip(str(v), 8), _clip(str(l), 11).upper()]
                        for v, l in stats[:3]]
    elif kind == "image":
        pool = list(bundle.get(source) or [])
        if not pool:
            return None
        # variant selects which upload this appearance shows, so three
        # screenshots give three screens rather than the same one three times
        picked = pool[variant % len(pool)]
        fit = picked.get("fit", "panel")
        out["file"] = picked["file"]
        out["fit"] = fit
        out["y"] = 0 if fit == "full" else _panel_y(
            picked.get("height", 600), picked.get("position", "bottom"),
            bundle.get("captions", True))
        # each upload says what it is a picture of, so the screen says it too
        out["eyebrow"] = picked.get("eyebrow", "")
        if picked.get("caption"):
            out["caption"] = _clip(picked["caption"], 44)
        # a generated picture has no text in it by design; the words it
        # needs are painted over it here
        if picked.get("heading"):
            out["label"] = _clip(picked["heading"], 40)
    elif kind == "counter":
        target, label = _countable(bundle, source, variant)
        if target is None:
            return None
        out["target"], out["label"] = target, label
    elif kind == "terminal":
        lines = list(bundle.get(source) or [])
        if not lines:
            return None
        out["lines"] = [_clip(line, 42) for line in lines[:3]]
        out.setdefault("title", bundle.get("command_title", ""))
    elif kind == "scroll":
        shot = bundle.get(source)
        if not shot:
            return None
        out["file"] = shot["file"]
        out["label"] = shot.get("label", "")
    elif kind == "clip":
        pool = list(bundle.get(source) or [])
        if not pool:
            return None
        picked = pool[variant % len(pool)]
        out["dir"] = picked["dir"]
        out["fps"] = int(picked.get("fps", 30))
        out["frames"] = int(picked.get("frames", 1))
        out["label"] = picked.get("label", "")
        out["eyebrow"] = picked.get("label", "")
    elif kind in ("factlist", "tiles"):
        rows = list(bundle.get(source) or [])
        want = int(options.get("rows", 4))
        window = rows[variant * want:(variant + 1) * want] or rows[:want]
        if not window:
            return None
        out["rows"] = [[_clip(str(l), 24), _clip(str(v), 34)] for l, v in window]
    else:
        return None
    return out


#: The band a panel may occupy: below the eyebrow, above the caption band.
#: The band a panel may occupy. The floor depends on whether captions are
#: burned in, because they are drawn over everything else.
#:
#: This used to be a flat 1470, and the burned-in captions start at 1450 -- so
#: *every* bottom-placed panel overlapped them by 20px. The preview built to
#: warn about collisions duly warned about this one on the very first
#: screenshot anyone placed, which is how it was found. With captions off the
#: floor is the safe area instead, because there is nothing there to collide
#: with and a screenshot may as well have the room.
PANEL_TOP = 380
CAPTION_TOP = 1450
PANEL_BOTTOM_CAPTIONED = CAPTION_TOP - 10
PANEL_BOTTOM_BARE = 1580
#: Kept for anything still reading a single floor; the captioned case is the
#: one that constrains.
PANEL_BOTTOM = PANEL_BOTTOM_CAPTIONED


def panel_floor(captions: bool) -> int:
    return PANEL_BOTTOM_CAPTIONED if captions else PANEL_BOTTOM_BARE


def _panel_y(height: int, position: str, captions: bool = True) -> int:
    """Where a panel of this height sits, given where it was asked to sit.

    Bottom is the default because the eyebrow is at the top and a panel placed
    there covers it -- which is what one rendered reel did, with "THE REPO"
    printed across a screenshot.
    """
    floor = panel_floor(captions)
    if position == "top":
        return PANEL_TOP
    if position == "centre":
        return PANEL_TOP + max(0, (floor - PANEL_TOP - height) // 2)
    return max(PANEL_TOP, floor - height)


def _countable(bundle: dict, source: str, variant: int):
    """A stat that is a plain number, so it can tick up rather than appear."""
    candidates = list(bundle.get(source) or [])
    if isinstance(bundle.get(source), (int, float)):
        return int(bundle[source]), None
    # `variant` was accepted and then ignored, so a layout with
    # `repeat_with: stats` counted to the same number every time it appeared.
    # Rotating by the variant makes a repeat show the next countable stat;
    # rotation by 0 is the identity, so the single-appearance case is unchanged.
    if candidates and variant:
        variant %= len(candidates)
        candidates = candidates[variant:] + candidates[:variant]
    for value, label in candidates:
        # stats are compacted for the cards ("38K"), and a counter ticking to
        # 38,000 is the same claim -- so read the compact form back out
        raw = str(value).replace(",", "").rstrip("+").upper()
        scale = {"K": 1_000, "M": 1_000_000, "B": 1_000_000_000}.get(raw[-1:], 1)
        digits = raw[:-1] if scale > 1 else raw
        try:
            return int(float(digits) * scale), str(label).upper()
        except ValueError:
            continue
    return None, None


def build_source(
    content: ReelContent, *, total: float, audio_rel: str, phrases_rel: str,
    endcard_seconds: float = 3.2, captions: bool = True,
    segments: list[tuple[float, float]] | None = None,
    catalogue_name: str | None = None,
    images: list[dict] | None = None,
    family: str = "bloom",
    scroll: dict | None = None,
    clips: list[dict] | None = None,
) -> str:
    """Assemble the module source for this content.

    `family` picks the design language: "bloom" (sbkit) or "slab" (slab.py).
    Both consume the same resolved DATA -- only the emitted module and the
    screen catalogue differ -- so content work is shared between them.
    """
    if family not in FAMILIES:
        raise ValueError(f"unknown storyboard family {family!r}; "
                         f"available: {', '.join(sorted(FAMILIES))}")
    catalogue_name = catalogue_name or FAMILIES[family]["catalogue"]
    facts = [(row.label, _stat_value(row.value)) for row in content.fact_sheet]
    commands = [content.cover.cmd] if content.cover.prompt else []
    if not commands:
        commands = [content.cover.cmd or content.tagline]

    hook_lines = [line for line in content.cover.hook if line.strip()][:3]
    if not hook_lines:
        hook_lines = [content.display_name]

    point_lines = []
    for scene in content.scenes[2:4]:
        first = scene.title.strip()
        if first:
            point_lines.append(_clip(first, 26))
    if not point_lines:
        point_lines = [_clip(content.tagline, 26)]

    bundle = {
        "captions": bool(captions),
        "images": list(images or []),
        "clips": list(clips or []),
        "scroll": dict(scroll) if scroll else None,
        "image_eyebrow": (images[0]["eyebrow"] if images else "A LOOK"),
        "clip_eyebrow": (clips[0].get("label") if clips else "") or "IN MOTION",
        "hook_lines": hook_lines,
        "point_lines": point_lines,
        "stats": [list(x) for x in content.cover.stats],
        "facts": facts,
        "commands": commands,
        "tagline": content.tagline,
        "quote": content.tagline,
        "command_title": content.display_name.lower(),
        "eyebrow": _clip(content.cover.eyebrow, 34).upper(),
        "points_eyebrow": (_clip(content.scenes[2].title, 34).upper()
                           if len(content.scenes) > 2 else "THE INTERESTING PART"),
    }

    spans = scene_spans(
        segments or [(0.0, total)],
        [p.scene_index for p in content.phrases], total, endcard_seconds,
    )
    screens = _build_screens(spans, bundle, catalogue_name)

    data = {
        "captions": bool(captions),
        "screens": screens,
        "theme": {
            "bg": list(content.theme.bg), "accent": list(content.theme.accent),
            "accent_hi": list(content.theme.accent_hi), "pale": list(content.theme.pale),
            "glow": list(content.theme.glow), "support": list(content.theme.support),
            "seed": content.theme.base_seed, "bloom": content.theme.base_bloom,
        },
        "eyebrow": _clip(content.cover.eyebrow, 34).upper(),
        "hook_lines": hook_lines,
        "tagline": _clip(content.tagline, 56),
        "stats": [list(s) for s in content.cover.stats],
        "facts": facts,
        "commands": commands,
        "command_title": content.display_name.lower(),
        "command_eyebrow": "ONE COMMAND" if content.cover.prompt else "WHAT IT GIVES YOU",
        "points_eyebrow": (_clip(content.scenes[2].title, 34).upper()
                           if len(content.scenes) > 2 else "THE INTERESTING PART"),
        "point_lines": point_lines,
        "wordmark": content.cover.wordmark,
        "endcard_sub": _clip(content.tagline, 42),
        "url": content.repo_url.replace("https://", "").replace("http://", ""),
        "url2": content.cover.cmd if content.cover.prompt else "",
        "cta": "SAVE THIS FOR YOUR NEXT SETUP",
        "tag": content.repo_url.rstrip("/").split("/")[-2:] and "/".join(
            content.repo_url.rstrip("/").split("/")[-2:]
        ),
        "endcard_seconds": endcard_seconds,
    }

    if family == "slab":
        data["theme"]["fields"] = slab_ramp(data["theme"])
        data["captions"] = False

    return FAMILIES[family]["template"]().format(
        slug=content.slug, audio=audio_rel, phrases=phrases_rel, total=total,
        # a Python literal, not JSON: the two agree on strings, numbers, lists
        # and dicts, but JSON writes booleans as `true` and this module is
        # executed rather than parsed
        data=pformat(data, indent=4, width=88, sort_dicts=False),
    )


def _build_screens(spans, bundle: dict, catalogue_name: str) -> list[dict]:
    """One resolved screen per span: which layout, which text, at which pixel.

    The last span is always the end card, whatever the catalogue's closer says,
    because `endcard_seconds` already carved that time out of the timeline.
    """
    from app.render.screens import pick

    chosen = pick(len(spans), bundle, catalogue_name)
    screens = []
    for index, ((start, end), (layout, variant)) in enumerate(zip(spans, chosen)):
        slots = [resolved for resolved in
                 (_resolve(slot, bundle, variant) for slot in layout.slots)
                 if resolved]
        is_end = index == len(spans) - 1
        eyebrow = layout.eyebrow
        if eyebrow.startswith("@"):            # pull the text from the content
            eyebrow = str(bundle.get(eyebrow[1:], "") or "")
        # a slot may name its own: three screenshots of different things get
        # three different headings rather than one generic one
        for resolved in slots:
            if resolved.get("eyebrow"):
                eyebrow = resolved["eyebrow"]
                break
        # a scroll paces itself across its own screen, and the span is not
        # knowable at _resolve time -- only here
        for resolved in slots:
            if resolved.get("kind") == "scroll":
                resolved["dur"] = round(end - start, 3)
        screens.append({
            "id": layout.id, "start": round(start, 3), "end": round(end, 3),
            "eyebrow": "" if is_end else eyebrow[:34].upper(),
            "is_end": is_end,
            "slots": slots if not is_end else [{"kind": "endcard"}],
        })
    return screens

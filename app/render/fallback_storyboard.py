def slab_ramp(theme: dict) -> list[list[int]]:
    """A six-stop field ramp from the content's own palette.

    Slab needs a colour per scene, not one accent, and consecutive fields have
    to differ enough that the wipe reads. Alternating light / dark / saturated
    guarantees that whatever palette the content stage picked.
    """
    accent = list(theme["accent"])
    support = list(theme.get("support") or accent)
    light = [240, 238, 233]
    ink = [max(14, min(28, c)) for c in theme.get("bg", [18, 18, 20])]
    return [light, ink, accent, light, support, ink]


def template_constants() -> dict[str, float]:
    """The constants defined inside TEMPLATE, read back out.

    The safe area and the full-bleed treatments are declared in the emitted
    module, not here -- that is where they are used, and moving them would mean
    two definitions. But the reel-frame preview in the browser needs them, and a
    second copy typed into JavaScript is exactly the drift this avoids. So they
    are parsed from the one place they exist.
    """
    import ast
    import re as _re

    out: dict[str, float] = {}
    for line in TEMPLATE.splitlines():
        match = _re.match(r"^([A-Z][A-Z_, ]*)\s*=\s*(.+)$", line.strip())
        if not match:
            continue
        names = [n.strip() for n in match.group(1).split(",") if n.strip()]
        try:
            value = ast.literal_eval(match.group(2))
        except (ValueError, SyntaxError):
            continue
        values = value if isinstance(value, tuple) else (value,)
        if len(names) != len(values):
            continue
        for name, item in zip(names, values):
            if isinstance(item, (int, float)):
                out[name] = item
    return out


